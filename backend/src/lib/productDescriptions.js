function productDescription(product) {
  const summary = PRODUCT_DESCRIPTION_BY_ID[Number(product.id)];
  return summary || product.description;
}

function canonicalLine(line) {
  return String(line || '')
    .toLocaleLowerCase('th')
    .replace(/^[^\p{L}\p{N}]+/u, '')
    .replace(/[^\p{L}\p{N}]+/gu, '');
}

function deduplicateDescriptionLines(value) {
  const seen = new Set();

  return String(value || '')
    .replace(/\r/g, '')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => {
      if (!line || /^[\p{Pd}_=—–─\s]{4,}$/u.test(line)) return false;
      const canonical = canonicalLine(line);
      if (canonical.length < 5) return true;
      if (seen.has(canonical)) return false;
      seen.add(canonical);
      return true;
    })
    .join('\n');
}

